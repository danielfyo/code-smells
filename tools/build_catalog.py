#!/usr/bin/env python3
"""Generate catalog.json, docs/CATALOG.md and <language>/INDEX.md from tools/catalog_data.py."""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from catalog_data import CATEGORIES, DOC_FOCUSED, SMELLS  # noqa: E402

LANG_META = {
    "python": ("python", "Python 3.11+", "cd python && python3 -m pytest"),
    "csharp": ("csharp", "C# 12 / .NET 8", "dotnet test CodeSmells.sln  # from the repo root"),
    "react-ts": ("react-ts", "React 19 + TypeScript 5", "cd react-ts && npm ci && npm run check"),
    "go": ("go", "Go 1.24", "cd go && go vet ./... && go test ./..."),
    "angular": ("angular", "Angular 22", "cd angular && npm ci && npm run check"),
}
LANG_LABEL = {"python": "Python", "csharp": "C#", "react-ts": "React/TS", "go": "Go", "angular": "Angular"}


def pascal(s: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in s.replace("_", "-").split("-"))


def snake(s: str) -> str:
    return s.replace("-", "_").lower()


def code_paths(cat_code: str, slug: str, langs: list[str]) -> dict[str, str]:
    out = {}
    if "python" in langs:
        out["python"] = f"python/code_smells/{cat_code}/{snake(slug)}/"
    if "csharp" in langs:
        out["csharp"] = f"csharp/src/CodeSmells/{pascal(cat_code)}/{pascal(slug)}/"
    if "react-ts" in langs:
        out["react-ts"] = f"react-ts/src/smells/{cat_code}/{slug}/"
    if "go" in langs:
        out["go"] = f"go/smells/{cat_code}/{slug}/"
    if "angular" in langs:
        out["angular"] = f"angular/src/smells/{cat_code}/{slug}/"
    return out


def build() -> list[dict]:
    catalog, n = [], 0
    for doc_dir, code_dir, name, desc in CATEGORIES:
        items = []
        for slug, smell_name, sources, summary, langs in SMELLS[code_dir]:
            n += 1
            items.append({
                "id": f"CS{n:03d}", "slug": slug, "name": smell_name, "sources": sources,
                "summary": summary, "languages": langs, "doc": f"docs/smells/{doc_dir}/{slug}.md",
                "code": code_paths(code_dir, slug, langs), "doc_focused": slug in DOC_FOCUSED,
            })
        catalog.append({"dir": doc_dir, "code_dir": code_dir, "name": name,
                        "description": desc, "smells": items})
    return catalog


def write_catalog_md(catalog: list[dict]) -> None:
    total = sum(len(c["smells"]) for c in catalog)
    lines = ["# Code Smell Catalog", "",
             f"Total: **{total} code smells** in **{len(catalog)} categories**. "
             "Generated by `tools/build_catalog.py` — do not edit by hand.", "",
             "## Categories", ""]
    lines += [f"- [{c['name']}](#{c['dir']}) — {len(c['smells'])} smells" for c in catalog]
    lines.append("")
    for c in catalog:
        lines += [f'<a id="{c["dir"]}"></a>', "", f"## {c['name']}", "", c["description"], "",
                  "| ID | Smell | Source | Summary | Code |", "|---|---|---|---|---|"]
        for s in c["smells"]:
            doc_link = "smells/" + s["doc"].removeprefix("docs/smells/")
            code = " · ".join(f"[{LANG_LABEL[lang]}](../{p})" for lang, p in s["code"].items())
            lines.append(f"| {s['id']} | [**{s['name']}**]({doc_link}) | {s['sources']} | {s['summary']} | {code} |")
        lines.append("")
    (ROOT / "docs" / "CATALOG.md").write_text("\n".join(lines), encoding="utf-8")


def write_language_indexes(catalog: list[dict]) -> None:
    for lang, (folder, label, cmd) in LANG_META.items():
        out = [f"# Code Smell Index — {label}", "",
               "Generated by `tools/build_catalog.py`. Every folder contains the **smelly** version, "
               "the **refactored** version and tests proving both behave the same "
               "(or exposing the bug the smell causes).", "",
               f"Run everything: `{cmd}`", ""]
        for c in catalog:
            rows = [s for s in c["smells"] if lang in s["code"]]
            if not rows:
                continue
            out += [f"## {c['name']}", "", "| ID | Smell | Code | Explanation |", "|---|---|---|---|"]
            for s in rows:
                rel = s["code"][lang].removeprefix(folder + "/")
                out.append(f"| {s['id']} | {s['name']} | [`{rel}`]({rel}) | [docs](../{s['doc']}) |")
            out.append("")
        (ROOT / folder / "INDEX.md").write_text("\n".join(out), encoding="utf-8")


def main() -> None:
    catalog = build()
    (ROOT / "catalog.json").write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    write_catalog_md(catalog)
    write_language_indexes(catalog)
    print(f"{sum(len(c['smells']) for c in catalog)} smells in {len(catalog)} categories")


if __name__ == "__main__":
    main()
